import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { FRAMEWORK_PAGES } from "../frameworks.mjs";
import { docsPages } from "../scripts/lib/load.ts";
import { parseFrontmatter } from "../scripts/lib/markdown.ts";
import { DIST } from "../scripts/lib/paths.ts";

// `pnpm test` runs `astro build` before vitest, so dist is newer than the change.
const html = readFileSync(`${DIST}docs/index.html`, "utf8");

/**
 * The links of the sidebar, by the label of their top-level group. A link
 * outside each group (Home, FAQ) is under "". A nested group (such as the
 * cli folder of Reference) counts as its top-level group.
 */
function sidebarGroups(page: string): Map<string, { href: string; label: string }[]> {
  const start = page.indexOf('<ul class="top-level');
  const end = page.indexOf("</sl-sidebar-state-persist>", start);
  if (start < 0 || end < 0) throw new Error("the page has no sidebar");
  const groups = new Map<string, { href: string; label: string }[]>();
  let depth = 0;
  let group = "";
  const token =
    /<details\b|<\/details>|<span class="group-label[^"]*"><span[^>]*>([^<]*)<\/span>|<a href="([^"]*)"[^>]*><span[^>]*>([^<]*)<\/span>/g;
  for (const m of page.slice(start, end).matchAll(token)) {
    if (m[0].startsWith("<details")) depth += 1;
    else if (m[0] === "</details>") {
      depth -= 1;
      if (depth === 0) group = "";
    } else if (m[1] !== undefined) {
      if (depth === 1) group = m[1];
    } else {
      const links = groups.get(group) ?? [];
      links.push({ href: m[2] ?? "", label: m[3] ?? "" });
      groups.set(group, links);
    }
  }
  return groups;
}

/** The lines of the `sidebar:` map of a page's frontmatter, without the indent. */
function sidebarKeys(source: string): string[] {
  const fm = parseFrontmatter(source);
  if (!fm) return [];
  const lines = source.split("\n").slice(1, fm.bodyLine - 2);
  const at = lines.indexOf("sidebar:");
  if (at < 0) return [];
  const keys: string[] = [];
  for (const line of lines.slice(at + 1)) {
    if (!line.startsWith("  ")) break;
    keys.push(line.trim());
  }
  return keys;
}

const urls = FRAMEWORK_PAGES.map(({ slug }) => `/${slug}/`);

describe("the Frameworks sidebar group (plan 11d2 Task 16)", () => {
  it("lists each page of FRAMEWORK_PAGES once under Frameworks, in order", () => {
    expect(FRAMEWORK_PAGES.length).toBeGreaterThan(0);
    // Rule 1: the group comes after "Getting started" and before "How-to guides".
    const labels = [...sidebarGroups(html).keys()];
    const at = labels.indexOf("Getting started");
    expect(labels.slice(at, at + 3)).toEqual(["Getting started", "Frameworks", "How-to guides"]);
    expect(sidebarGroups(html).get("Frameworks")).toEqual(
      FRAMEWORK_PAGES.map(({ label, slug }) => ({ href: `/${slug}/`, label })),
    );
  });

  it("lists no page of FRAMEWORK_PAGES under another group", () => {
    const groups = sidebarGroups(html);
    expect(groups.size).toBeGreaterThan(1);
    const elsewhere = [...groups]
      .filter(([label]) => label !== "Frameworks")
      .flatMap(([label, links]) =>
        links.filter((l) => urls.includes(l.href)).map((l) => `${label}: ${l.href}`),
      );
    expect(elsewhere).toEqual([]);
  });

  it("marks each page of FRAMEWORK_PAGES as hidden from the autogenerated groups", () => {
    const pages = docsPages();
    const marks = FRAMEWORK_PAGES.map(({ slug }) => {
      const found = pages.filter((p) => p.path.replace(/\.mdx?$/, "") === slug);
      return {
        slug,
        files: found.length,
        hidden: found.every((p) => sidebarKeys(p.source).includes("hidden: true")),
      };
    });
    expect(marks).toEqual(FRAMEWORK_PAGES.map(({ slug }) => ({ slug, files: 1, hidden: true })));
  });

  it("lists each hidden page in FRAMEWORK_PAGES", () => {
    // A hidden page leaves every autogenerated group. A hidden page that is
    // not in the list then has no place in the sidebar.
    const hidden = docsPages()
      .filter((p) => sidebarKeys(p.source).includes("hidden: true"))
      .map((p) => p.path.replace(/\.mdx?$/, ""))
      .sort();
    expect(hidden).toEqual(FRAMEWORK_PAGES.map(({ slug }) => slug).sort());
  });
});
