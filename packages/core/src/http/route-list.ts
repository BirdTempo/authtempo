/** The method of a route. */
export type RouteMethod = RouteEntry["method"];

/** One entry of `ROUTES` with its literal method and path (plan 11d). */
export type RouteLiteral = (typeof ROUTES)[number];

/**
 * A path that `ROUTES` holds for the method `M` (plan 11d). An SDK types its
 * paths with it, so a path that core does not serve fails the SDK's compile.
 */
export type RoutePath<M extends RouteMethod = RouteMethod> = Extract<
  RouteLiteral,
  { method: M }
>["path"];

type KeyOf<R> = R extends {
  readonly method: infer M extends string;
  readonly path: infer P extends string;
}
  ? `${M} ${P}`
  : never;

/**
 * `"<METHOD> <path>"` of one entry of `ROUTES` (plan 11g). The type is a
 * union of the literal keys, one per entry. So a route with a key that
 * `ROUTES` does not hold fails the compile. `routeKeyOf` builds the same key
 * from a mounted route.
 */
export type RouteKey = KeyOf<RouteLiteral>;

/**
 * The codes that the router answers for every route (plan 11g). `not_found`
 * is for a feature that is off. `origin_not_trusted` is for a POST from an
 * origin that is not trusted. `internal` is for an unhandled error. An entry
 * does not repeat them; the OpenAPI document adds them to each operation.
 */
export const ROUTER_CODES = [
  "not_found",
  "origin_not_trusted",
  "internal",
] as const satisfies readonly ErrorCode[];
export type RouterCode = (typeof ROUTER_CODES)[number];

/**
 * The codes of the operator routes that only a request with a session gets
 * (plan 12f): `operator_self` for the act of a platform operator on their
 * own user, and `impersonation_session` for a request of an impersonation
 * session. A request with an operator secret and no session, such as each
 * call of the CLI, never gets them. The CLI runbooks and the refusal texts
 * of the CLI leave them out.
 */
