import type { ErrorCode, OAuthErrorCode } from "../errors.js";

/**
 * Every route that core can serve, with the config that turns it on (plan
 * 11a). The docs routes page has one anchor for each entry, and its check
 * reads this list. `route-list.test.ts` proves that the router serves exactly
 * this list when every feature is on, so the list cannot drift from the
 * route files. A path is relative to `basePath`. `:provider` stands for each
 * configured social provider; Apple's callback is the one POST callback.
 * `ROUTE_FEATURES` (plan 11g) lists every feature once; the OpenAPI document
 * reads it, and the route list test holds it to the entries.
 */
export const ROUTE_FEATURES = [
  "session",
  "account",
  "accountDelete",
  "magicLink",
  "social",
  "passkey",
  "password",
  "totp",
  "emailOtp",
  "emailOtpReset",
  "handoff",
  "organizations",
  "tokens",
  "jwtMint",
  "operator",
  "operatorUsers",
  "operatorImpersonation",
  "oauth",
  "oauthRegistration",
  "oauthDevice",
  "openapi",
] as const;
export type RouteFeature = (typeof ROUTE_FEATURES)[number];

/**
 * The credential forms that a route takes (plan 11g). The OpenAPI document
 * writes each one as a security scheme.
 */
export type AuthForm =
  | "none" // no credential
  | "session" // the session cookie or a ts_ bearer
  | "apiToken" // a tk_ bearer
  | "sessionJwt" // a session JWT as the bearer (POST /token/live, plan 11d)
  | "accessToken" // an OAuth access token of the provider (userinfo)
  | "dpopAccessToken" // a DPoP-bound access token with its proof, RFC 9449 section 7.1 (plan 12e)
  | "operator" // Authorization: Operator <secret>
  | "initialAccessToken" // the initial access token of RFC 7591 as the bearer (plan 12e)
  | "clientSecretBasic"; // the client id and secret as HTTP Basic, RFC 6749 section 2.3.1 (plan 12e)

export interface RouteEntry {
  readonly method: "GET" | "POST";
  readonly path: string;
  /**
   * The config that turns the route on. `session`, `magicLink`, and `tokens`
   * are in every deployment; `emailOtp` and `jwtMint` are on by default;
   * `emailOtpReset` needs `emailOtp` and `password`; `totp` needs `password`;
   * `oauthRegistration` needs `oauth` with `registration.dynamic`;
   * `oauthDevice` needs `oauth` with `device` (plan 12e); `operator`
   * needs `operator.secretHash` (plan 11c) or `operator.secrets` (plan 12f), and `/operator/keys/rotate` also
   * needs `jwtMint` (plan 11c2). `operatorUsers` needs `operator.users`
   * (plan 12f). `operatorImpersonation` needs `operator.impersonation`
   * (plan 12f). `account` (plan 12a) is in every
   * deployment. `accountDelete` (plan 12a) is on by default; `account.delete:
   * false` turns it off. `openapi` (plan 11g) needs `openapi: true`.
   */
  readonly feature: RouteFeature;
  /** The credentials that the route takes. More than one means any one of them. */
  readonly auth: readonly AuthForm[];
  /** The codes of ERRORS that the route answers, without ROUTER_CODES. */
  readonly codes: readonly ErrorCode[];
  /** The codes of OAUTH_ERRORS that the route answers. Empty outside the provider routes. */
  readonly oauthCodes: readonly OAuthErrorCode[];
  /** The POST skips the router's Origin check: Apple's form_post callback, and the end-session form of a relying party (plan 12e). */
  readonly crossSiteForm?: true;
}

